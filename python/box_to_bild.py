"""Write a docking-box record as a ChimeraX BILD object for visual inspection.

usage:   python python/box_to_bild.py BOX_RECORD.json OUT.bild [--chimerax-script OUT.cxc]
example: python python/box_to_bild.py examples/box_murc_uma_chainE_24A.json box24.bild

The box is drawn in the coordinate frame recorded in the box record, which is
the frame of the source structure as read. It is therefore only meaningful
against a structure in that same frame: the deposited file, or a receptor
prepared from it without transformation. Design or refolded structures from
BoltzGen are in a different frame and must be superposed first.

This is a visual sanity check, not a validation. What it can show is whether
the box sits on the intended protein copy, whether it covers the pocket mouth,
and which pocket residues fall at or outside a face. What it cannot show is
whether the box is the right search region.

With `--chimerax-script`, a small `.cxc` file is written that opens a structure
and the box together; pass the structure path with `--structure`.
"""
from __future__ import annotations

import argparse
import shlex
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import box_geometry


def chimerax_path(path: Path | str) -> str:
    """Return an absolute path quoted for a ChimeraX command.

    ChimeraX splits command arguments on whitespace, so any path containing a
    space must be quoted, and a relative path would be resolved against
    whatever directory ChimeraX happens to be started in. Both are handled
    here rather than left to the caller. Double quotes are used, so an
    embedded double quote is escaped; backslashes are escaped first so the
    escape itself survives.
    """
    text = str(Path(path).resolve())
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def chimerax_script(structure: str | None, bild_path: Path,
                    record: dict) -> list[str]:
    """Return ChimeraX commands opening the structure, the box and the pocket.

    Paths are made absolute and quoted, so the script runs from any working
    directory and tolerates spaces in a path.

    The pocket residues are selected by *author* residue number on the author
    chain named in the record, which is how the deposited file and a prepared
    receptor are numbered. Insertion codes are not representable in this plain
    residue-number selection; the record's residue identifiers remain the
    authoritative list.
    """
    selection = record.get("selection", {})
    author_chain = selection.get("protein_author_chain_id")
    pocket = selection.get("pocket_author_residue_ids", [])
    lines = ["# Generated by python/box_to_bild.py. Review before trusting.",
             "set bgColor white"]
    if structure:
        lines += [f"open {chimerax_path(structure)}", "hide atoms",
                  "show cartoons", "color lightgray"]
    lines.append(f"open {chimerax_path(bild_path)}")
    if structure and author_chain and pocket:
        residues = ",".join(str(value) for value in pocket)
        lines += [
            f"show /{author_chain}:{residues} atoms",
            f"style /{author_chain}:{residues} stick",
            f"color /{author_chain}:{residues} goldenrod",
            f"# {len(pocket)} pocket residues at a "
            f"{selection.get('pocket_cutoff_angstrom')} A cutoff",
        ]
    ligand_residue_ids = selection.get("ligand_author_residue_ids", [])
    if structure and ligand_residue_ids:
        for identifier in ligand_residue_ids:
            chain, _, residue = identifier.partition(":")
            lines += [f"show /{chain}:{residue} atoms",
                      f"style /{chain}:{residue} ball",
                      f"color /{chain}:{residue} dodger blue"]
        lines.append(f"# recorded ligand selection: "
                     f"{selection.get('ligand_residues', ligand_residue_ids)}")
    lines.append("view")
    return lines


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("box_record", type=Path)
    parser.add_argument("output", type=Path, help="BILD file to write")
    parser.add_argument("--edge-radius", type=float, default=0.15,
                        help="Edge cylinder radius in A (default 0.15)")
    parser.add_argument("--transparency", type=float, default=0.8,
                        help="Transparency of the solid box body, 0-1 "
                             "(default 0.8)")
    parser.add_argument("--chimerax-script", type=Path,
                        help="Also write a .cxc opening the box and a structure")
    parser.add_argument("--structure", help="Structure path for the .cxc script")
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()

    if not 0.0 <= args.transparency <= 1.0:
        parser.error("--transparency must lie between 0 and 1.")
    try:
        record = box_geometry.read_record(args.box_record)
        lines = box_geometry.bild_lines(
            record, edge_radius_angstrom=args.edge_radius,
            transparency=args.transparency)
    except box_geometry.BoxError as error:
        parser.error(str(error))

    for destination in (args.output, args.chimerax_script):
        if destination is not None and destination.exists() and not args.overwrite:
            parser.error(f"{destination} already exists; pass --overwrite to replace it.")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")
    print(f"box     : {box_geometry.describe(record)}")
    print(f"wrote   : {args.output}")

    if args.chimerax_script:
        if not args.structure:
            print("NOTE no --structure given, so the .cxc opens the box alone.")
        script = chimerax_script(args.structure, args.output, record)
        args.chimerax_script.parent.mkdir(parents=True, exist_ok=True)
        args.chimerax_script.write_text("\n".join(script) + "\n")
        print(f"wrote   : {args.chimerax_script}")
        print(f"view    : chimerax {shlex.quote(str(args.chimerax_script.resolve()))}")


if __name__ == "__main__":
    main()
